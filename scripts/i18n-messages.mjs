// Regenerates src/i18n/messages.ts from every t("…"), tNow("…") and msg("…") call in src.
// Run with `npm run i18n` after adding or changing a UI string.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = new URL("../src/", import.meta.url).pathname;
const call = /\b(?:t|tNow|msg)\(\s*"((?:[^"\\]|\\.)*)"/g;
const found = new Set();

function walk(dir) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) {
      if (entry.name !== "i18n") walk(path);
    } else if (/\.tsx?$/.test(entry.name) && !/\.test\.tsx?$/.test(entry.name)) {
      for (const match of readFileSync(path, "utf8").matchAll(call)) {
        found.add(JSON.parse(`"${match[1]}"`));
      }
    }
  }
}

walk(root);
const messages = [...found].sort((a, b) => a.localeCompare(b, "en"));
writeFileSync(
  join(root, "i18n/messages.ts"),
  `// Generated by scripts/i18n-messages.mjs, do not edit.\nexport const MESSAGES = ${JSON.stringify(messages, null, 2)} as const;\n\nexport type Message = (typeof MESSAGES)[number];\n`,
);
console.log(`${messages.length} messages`);
